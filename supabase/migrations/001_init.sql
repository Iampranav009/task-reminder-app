-- Task Reminder App — Supabase schema (v1)
-- Run this in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Or with the Supabase CLI: supabase db push
--
-- v1 note: Row Level Security is ON, with a permissive policy for the
-- anon key so the single-user app works without login. Proper per-user
-- auth (Supabase Auth + RLS scoped to auth.uid()) comes next — do not
-- use this permissive policy for a multi-user production app.

create extension if not exists "pgcrypto";

-- Keep updated_at fresh on every change.
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Projects (main tasks)
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  due_date date,
  priority text not null default 'normal'
    check (priority in ('high_alert', 'high', 'normal', 'very_normal')),
  color text not null default '#0E7C6B',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
drop trigger if exists projects_set_updated_at on public.projects;
create trigger projects_set_updated_at
  before update on public.projects
  for each row execute function public.set_updated_at();

-- Tasks (one-off and daily)
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  notes text not null default '',
  project_id bigint references public.projects (id) on delete set null,
  due_date date,
  due_time time,
  kind text not null default 'task' check (kind in ('task', 'daily')),
  priority text not null default 'normal'
    check (priority in ('high_alert', 'high', 'normal', 'very_normal')),
  status text not null default 'todo' check (status in ('todo', 'done')),
  reminders_per_day integer not null default 0,
  completed_at timestamptz,
  daily_done_on date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists tasks_due_idx on public.tasks (due_date, due_time);
create index if not exists tasks_status_idx on public.tasks (status);
drop trigger if exists tasks_set_updated_at on public.tasks;
create trigger tasks_set_updated_at
  before update on public.tasks
  for each row execute function public.set_updated_at();

-- Ultron-scheduled reminders
create table if not exists public.ultron_reminders (
  id bigint generated by default as identity primary key,
  title text not null,
  task_id bigint references public.tasks (id) on delete set null,
  date date not null,
  time time not null,
  message text not null default '',
  fired boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists ultron_reminders_due_idx
  on public.ultron_reminders (date, time) where (fired = false);

-- App settings + profile (single row, id = 1).
-- Stored as JSON so the Settings/Profile shape can evolve without
-- a new migration for every toggle.
create table if not exists public.app_settings (
  id integer primary key default 1,
  settings jsonb not null default '{}'::jsonb,
  profile jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
drop trigger if exists app_settings_set_updated_at on public.app_settings;
create trigger app_settings_set_updated_at
  before update on public.app_settings
  for each row execute function public.set_updated_at();

-- Row Level Security: ON for every table, permissive anon policy for v1.
alter table public.projects enable row level security;
alter table public.tasks enable row level security;
alter table public.ultron_reminders enable row level security;
alter table public.app_settings enable row level security;

drop policy if exists "anon all" on public.projects;
create policy "anon all" on public.projects
  for all to anon using (true) with check (true);

drop policy if exists "anon all" on public.tasks;
create policy "anon all" on public.tasks
  for all to anon using (true) with check (true);

drop policy if exists "anon all" on public.ultron_reminders;
create policy "anon all" on public.ultron_reminders
  for all to anon using (true) with check (true);

drop policy if exists "anon all" on public.app_settings;
create policy "anon all" on public.app_settings
  for all to anon using (true) with check (true);

